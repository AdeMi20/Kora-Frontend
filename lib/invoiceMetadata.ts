/**
 * InvoiceMetadataV1 — canonical schema for invoice NFT metadata uploaded to IPFS.
 *
 * Conforms to the OpenSea / ERC-1155 metadata standard extended with
 * invoice-specific fields. All metadata uploaded via lib/ipfs.ts must
 * pass this schema before being pinned.
 *
 * Version: 1.0
 * Closes #121
 */

import { z } from "zod";
import { env } from "@/lib/env";
import { isValidCID, fetchFromIpfsWithFallback } from "./ipfs";

// ─── Constants ────────────────────────────────────────────────────────────────

export const METADATA_VERSION = "1.0" as const;

export const SUPPORTED_CURRENCIES = ["USDC", "EURC", "XLM"] as const;

export const SUPPORTED_JURISDICTIONS = [
  "US", "EU", "UK", "NG", "KE", "GH", "ZA", "OTHER",
] as const;

export const SUPPORTED_CATEGORIES = [
  "technology",
  "manufacturing",
  "logistics",
  "healthcare",
  "retail",
  "construction",
  "agriculture",
  "energy",
  "finance",
  "other",
] as const;

export const SUPPORTED_RISK_TIERS = [
  "AAA", "AA", "A", "BBB", "BB", "B", "CCC",
] as const;

// ─── InvoiceMetadataV1 Zod Schema ─────────────────────────────────────────────

/**
 * Full schema for invoice NFT metadata (version 1.0).
 *
 * Required fields follow the NFT metadata standard (name, description, image)
 * plus the invoice-specific fields needed for on-chain verification.
 *
 * Optional fields provide richer context for marketplace display and
 * risk assessment without breaking backward compatibility.
 */
export const invoiceMetadataV1Schema = z.object({
  // ── Versioning ──────────────────────────────────────────────────────────────
  /** Schema version — always "1.0" for this schema. Used for future migrations. */
  metadata_version: z.literal(METADATA_VERSION),

  // ── NFT Standard Fields (required) ─────────────────────────────────────────
  /** Human-readable name for the NFT (e.g. "Invoice INV-2024-0001"). */
  name: z.string().min(1, "name is required").max(256),

  /** Human-readable description of the invoice asset. */
  description: z.string().min(1, "description is required").max(2048),

  /**
   * URI of the NFT image — either an IPFS URI (ipfs://CID) or an
   * HTTPS gateway URL. This is the SVG invoice preview generated by
   * generateInvoiceSvg().
   */
  image: z
    .string()
    .min(1, "image is required")
    .refine(
      (v) => v.startsWith("ipfs://") || v.startsWith("https://"),
      "image must be an ipfs:// or https:// URI"
    ),

  // ── Invoice Identity (required) ─────────────────────────────────────────────
  /** Unique invoice identifier (e.g. "INV-2024-0001"). */
  invoice_number: z
    .string()
    .min(1, "invoice_number is required")
    .regex(/^[a-zA-Z0-9-]+$/, "invoice_number must be alphanumeric with hyphens"),

  /** Invoice face value in the smallest representable unit (e.g. USDC cents). */
  amount: z.number().positive("amount must be positive"),

  /** Currency code. */
  currency: z.enum(SUPPORTED_CURRENCIES),

  /**
   * ISO 8601 date string for when the invoice is due (e.g. "2025-03-01").
   * Used by the smart contract to enforce repayment deadlines.
   */
  due_date: z
    .string()
    .min(1, "due_date is required")
    .regex(/^\d{4}-\d{2}-\d{2}$/, "due_date must be YYYY-MM-DD"),

  // ── Parties (required) ──────────────────────────────────────────────────────
  /**
   * Issuer information — the SME that created the invoice.
   * Contains at minimum the wallet address; display name is optional.
   */
  issuer: z.object({
    /** Stellar public key of the issuer (G...). */
    address: z
      .string()
      .min(1, "issuer.address is required")
      .regex(/^G[A-Z2-7]{55}$/, "issuer.address must be a valid Stellar public key"),
    /** Human-readable display name (company name). */
    name: z.string().max(256).optional(),
  }),

  /**
   * Debtor information — the entity that owes the invoice amount.
   * May be partially or fully anonymized depending on privacy settings.
   */
  debtor: z.object({
    /** Display name or anonymized label (e.g. "Technology Company, Kenya"). */
    name: z.string().min(1, "debtor.name is required").max(256),
    /** Physical or registered address. Omitted when privacy = anonymized. */
    address: z.string().max(512).optional(),
    /** Privacy level applied to this debtor's information. */
    privacy: z.enum(["full", "partial", "anonymized"]).default("full"),
  }),

  // ── Optional Enrichment Fields ──────────────────────────────────────────────
  /** ISO 3166-1 alpha-2 country code or region code (e.g. "KE", "EU"). */
  jurisdiction: z.enum(SUPPORTED_JURISDICTIONS).optional(),

  /** Industry category of the invoice. */
  category: z.enum(SUPPORTED_CATEGORIES).optional(),

  /** Risk tier assigned by the protocol's risk engine. */
  risk_tier: z.enum(SUPPORTED_RISK_TIERS).optional(),

  /**
   * Discount rate as a decimal (e.g. 0.05 = 5%).
   * Represents the yield offered to investors.
   */
  discount_rate: z
    .number()
    .min(0, "discount_rate must be >= 0")
    .max(1, "discount_rate must be <= 1 (100%)")
    .optional(),

  /**
   * IPFS CID of the original invoice PDF document.
   * Allows anyone to verify the underlying document.
   */
  ipfs_document_cid: z
    .string()
    .regex(
      /^(Qm[1-9A-HJ-NP-Za-km-z]{44}|bafy[a-z2-7]{52,})$/,
      "ipfs_document_cid must be a valid IPFS CID (v0 or v1)"
    )
    .optional(),

  /**
   * External URL for the NFT — typically the marketplace listing page.
   * Displayed by NFT explorers as a "View on Kora" link.
   */
  external_url: z
    .string()
    .url("external_url must be a valid URL")
    .optional(),

  /**
   * Structured attributes array following the OpenSea metadata standard.
   * Enables trait-based filtering in NFT marketplaces.
   */
  attributes: z
    .array(
      z.object({
        trait_type: z.string().min(1),
        value: z.union([z.string(), z.number()]),
        display_type: z
          .enum(["number", "boost_number", "boost_percentage", "date"])
          .optional(),
      })
    )
    .optional(),
});

// ─── Derived Types ────────────────────────────────────────────────────────────

export type InvoiceMetadataV1 = z.infer<typeof invoiceMetadataV1Schema>;

/** Input type before version field is added (used by builders). */
export type InvoiceMetadataV1Input = Omit<InvoiceMetadataV1, "metadata_version">;

const NON_TEXT_ELEMENTS = "script, style, template, noscript, iframe, object";

/**
 * Strips all markup from a plain-text field. Uses the platform's inert
 * DOMParser when available (browser / jsdom); otherwise falls back to removing
 * non-text elements with their contents, then any remaining tags.
 */
export function sanitizeText(text: string): string {
  if (!text) return "";
  if (typeof DOMParser !== "undefined") {
    const doc = new DOMParser().parseFromString(text, "text/html");
    doc.querySelectorAll(NON_TEXT_ELEMENTS).forEach((el) => el.remove());
    return doc.body.textContent ?? "";
  }
  return text
    .replace(/<(script|style|template|noscript|iframe|object)\b[^>]*>[\s\S]*?<\/\1\s*>/gi, "")
    .replace(/<[^>]*>/g, "");
}

export function sanitizeInvoiceMetadata(metadata: InvoiceMetadataV1): InvoiceMetadataV1 {
  const sanitized = { ...metadata };
  sanitized.name = sanitizeText(metadata.name);
  sanitized.description = sanitizeText(metadata.description);

  if (metadata.issuer) {
    sanitized.issuer = {
      ...metadata.issuer,
      name: metadata.issuer.name ? sanitizeText(metadata.issuer.name) : undefined,
    };
  }

  if (metadata.debtor) {
    sanitized.debtor = {
      ...metadata.debtor,
      name: sanitizeText(metadata.debtor.name),
      address: metadata.debtor.address ? sanitizeText(metadata.debtor.address) : undefined,
    };
  }

  if (metadata.attributes) {
    sanitized.attributes = metadata.attributes.map((attr) => ({
      ...attr,
      trait_type: sanitizeText(attr.trait_type),
      value: typeof attr.value === "string" ? sanitizeText(attr.value) : attr.value,
    }));
  }

  return sanitized;
}

/**
 * Validate raw metadata against the InvoiceMetadataV1 schema.
 *
 * Returns a typed result object — never throws.
 *
 * @example
 * const result = validateInvoiceMetadata(raw);
 * if (!result.success) {
 *   console.error(result.errors);
 * }
 */
export function validateInvoiceMetadata(
  raw: unknown
): { success: true; data: InvoiceMetadataV1 } | { success: false; errors: string[] } {
  const result = invoiceMetadataV1Schema.safeParse(raw);
  if (result.success) {
    return { success: true, data: sanitizeInvoiceMetadata(result.data) };
  }
  const errors = result.error.issues.map(
    (issue) => `${issue.path.join(".")}: ${issue.message}`
  );
  return { success: false, errors };
}

function canonicalizeMetadata(value: unknown): string {
  if (Array.isArray(value)) {
    return `[${value.map(canonicalizeMetadata).join(",")}]`;
  }
  if (value && typeof value === "object" && !(value instanceof Date)) {
    const sortedKeys = Object.keys(value as Record<string, unknown>).sort();
    return `{${sortedKeys
      .map((key) => `${JSON.stringify(key)}:${canonicalizeMetadata((value as Record<string, unknown>)[key])}`)
      .join(",")}}`;
  }
  return JSON.stringify(value);
}

export async function verifyMetadataIntegrity(
  cid: string,
  metadata: unknown
): Promise<boolean> {
  if (env.NEXT_PUBLIC_ENABLE_MOCK_DATA) {
    return true;
  }
  if (!cid || typeof cid !== "string" || !isValidCID(cid)) {
    return false;
  }
  try {
    // Rotate across gateways so a single gateway outage doesn't fail
    // verification. We compare canonicalized content, so integrity is asserted
    // by content equality here; the CID hash check runs inside the fetch too.
    const { text } = await fetchFromIpfsWithFallback(cid, { timeoutMs: 10_000 });
    const remote = JSON.parse(text);
    return canonicalizeMetadata(remote) === canonicalizeMetadata(metadata);
  } catch (error) {
    console.warn("Invoice metadata integrity verification failed", error);
    return false;
  }
}

/**
 * Parse and validate metadata, throwing a descriptive error on failure.
 * Use this in upload flows where invalid metadata should abort the operation.
 *
 * @throws {Error} with a human-readable list of validation failures
 */
export function parseInvoiceMetadata(raw: unknown): InvoiceMetadataV1 {
  const result = validateInvoiceMetadata(raw);
  if (!result.success) {
    throw new Error(
      `Invalid invoice metadata (v${METADATA_VERSION}):\n${result.errors.join("\n")}`
    );
  }
  return result.data;
}

// ─── Metadata Builder ─────────────────────────────────────────────────────────

/**
 * Build a validated InvoiceMetadataV1 object from raw invoice form data.
 * Automatically adds the metadata_version field and constructs the
 * attributes array for NFT marketplace compatibility.
 *
 * @param input - Invoice data without the version field
 * @returns Validated InvoiceMetadataV1 object
 * @throws {Error} if the resulting metadata fails schema validation
 */
export function buildInvoiceMetadata(
  input: InvoiceMetadataV1Input
): InvoiceMetadataV1 {
  const raw: InvoiceMetadataV1 = {
    metadata_version: METADATA_VERSION,
    ...input,
    // Auto-generate attributes array if not provided
    attributes: input.attributes ?? buildAttributes(input),
  };
  return parseInvoiceMetadata(raw);
}

/**
 * Build the OpenSea-compatible attributes array from invoice fields.
 * This enables trait-based filtering in NFT marketplaces.
 */
function buildAttributes(
  input: InvoiceMetadataV1Input
): InvoiceMetadataV1["attributes"] {
  const attrs: NonNullable<InvoiceMetadataV1["attributes"]> = [
    { trait_type: "Invoice Number", value: input.invoice_number },
    { trait_type: "Currency", value: input.currency },
    { trait_type: "Amount", value: input.amount, display_type: "number" },
    { trait_type: "Due Date", value: input.due_date },
  ];

  if (input.jurisdiction) {
    attrs.push({ trait_type: "Jurisdiction", value: input.jurisdiction });
  }
  if (input.category) {
    attrs.push({ trait_type: "Category", value: input.category });
  }
  if (input.risk_tier) {
    attrs.push({ trait_type: "Risk Tier", value: input.risk_tier });
  }
  if (input.discount_rate !== undefined) {
    attrs.push({
      trait_type: "Discount Rate",
      value: Math.round(input.discount_rate * 100),
      display_type: "boost_percentage",
    });
  }

  return attrs;
}

// ─── Schema Versioning & Migration (#392) ─────────────────────────────────────

/** Schema versions we can detect. "legacy" = pre-versioned camelCase metadata. */
export type MetadataVersion = "1.0" | "legacy";

/** Versions we can render natively without migration. */
export const SUPPORTED_METADATA_VERSIONS = [METADATA_VERSION] as const;

/**
 * Legacy (pre-#121) invoice metadata schema.
 *
 * Older on-chain CIDs point at metadata written before the versioned V1 schema
 * existed. That shape used camelCase keys and had no `metadata_version` field.
 * We keep a lenient parser so those NFTs still render and can be migrated to V1.
 */
export const legacyInvoiceMetadataSchema = z.object({
  name: z.string().optional(),
  description: z.string().optional(),
  image: z.string().optional(),
  invoiceNumber: z.string().min(1),
  issuerName: z.string().optional(),
  issuerAddress: z.string().min(1),
  debtorName: z.string().min(1),
  debtorAddress: z.string().optional(),
  amount: z.number().positive(),
  currency: z.string().min(1),
  issueDate: z.string().optional(),
  dueDate: z.string().min(1),
  description_: z.string().optional(),
  jurisdiction: z.string().optional(),
  category: z.string().optional(),
  documentHash: z.string().optional(),
  documentUrl: z.string().optional(),
});

export type LegacyInvoiceMetadata = z.infer<typeof legacyInvoiceMetadataSchema>;

/**
 * Detect which metadata schema a raw IPFS payload conforms to.
 *
 * @returns "1.0"    — has metadata_version === "1.0"
 * @returns "legacy" — no version field but recognizably invoice metadata
 * @returns "unknown" — unrecognized / not invoice metadata
 */
export function detectMetadataVersion(raw: unknown): MetadataVersion | "unknown" {
  if (!raw || typeof raw !== "object" || Array.isArray(raw)) return "unknown";
  const obj = raw as Record<string, unknown>;

  if (typeof obj.metadata_version === "string") {
    return obj.metadata_version === METADATA_VERSION ? "1.0" : "unknown";
  }

  // No version field — infer legacy from recognizable invoice fields.
  const looksLikeInvoice =
    (typeof obj.invoiceNumber === "string" || typeof obj.invoice_number === "string") &&
    (typeof obj.amount === "number" || typeof obj.amount === "string");
  return looksLikeInvoice ? "legacy" : "unknown";
}

/** Normalize an ISO date / date-time string to YYYY-MM-DD. */
function toDateOnly(value: string | undefined): string {
  if (!value) return "";
  return value.slice(0, 10);
}

/**
 * Migrate a legacy metadata object to the InvoiceMetadataV1 input shape.
 *
 * Best-effort field mapping — the result is still run through the V1 schema by
 * {@link parseAnyInvoiceMetadata}, so genuinely malformed legacy data surfaces
 * a clear validation error rather than a silent bad migration.
 */
export function migrateLegacyToV1(
  legacy: LegacyInvoiceMetadata
): InvoiceMetadataV1Input {
  const currency = String(legacy.currency).toUpperCase();
  const image =
    legacy.image ||
    (legacy.documentHash ? `ipfs://${legacy.documentHash}` : undefined) ||
    legacy.documentUrl ||
    "";

  return {
    name: legacy.name || `Invoice ${legacy.invoiceNumber}`,
    description:
      legacy.description ||
      `Tokenized invoice ${legacy.invoiceNumber} (migrated from legacy schema)`,
    image,
    invoice_number: legacy.invoiceNumber,
    amount: legacy.amount,
    currency: currency as InvoiceMetadataV1Input["currency"],
    due_date: toDateOnly(legacy.dueDate),
    issuer: {
      address: legacy.issuerAddress,
      name: legacy.issuerName || undefined,
    },
    debtor: {
      name: legacy.debtorName,
      address: legacy.debtorAddress || undefined,
      privacy: "full",
    },
    jurisdiction: legacy.jurisdiction as InvoiceMetadataV1Input["jurisdiction"],
    category: legacy.category as InvoiceMetadataV1Input["category"],
    ipfs_document_cid: legacy.documentHash,
  };
}

/** Result of parsing metadata of any supported version. */
export type ParsedInvoiceMetadata = {
  /** The detected source schema version. */
  version: MetadataVersion;
  /** The metadata normalized to the current V1 schema. */
  data: InvoiceMetadataV1;
};

/**
 * Parse invoice metadata of any supported schema version into a normalized
 * InvoiceMetadataV1 object.
 *
 * - V1 payloads are validated directly.
 * - Legacy payloads are parsed, migrated to V1, then validated.
 * - Unknown payloads throw a descriptive error.
 *
 * @throws {Error} if the schema is unrecognized or the (migrated) data fails
 *                 V1 validation.
 */
export function parseAnyInvoiceMetadata(raw: unknown): ParsedInvoiceMetadata {
  const version = detectMetadataVersion(raw);

  if (version === "1.0") {
    return { version, data: parseInvoiceMetadata(raw) };
  }

  if (version === "legacy") {
    const parsed = legacyInvoiceMetadataSchema.safeParse(raw);
    if (!parsed.success) {
      const errors = parsed.error.issues.map(
        (issue) => `${issue.path.join(".")}: ${issue.message}`
      );
      throw new Error(
        `Invalid legacy invoice metadata:\n${errors.join("\n")}`
      );
    }
    const migrated = buildInvoiceMetadata(migrateLegacyToV1(parsed.data));
    return { version, data: migrated };
  }

  throw new Error(
    "Unrecognized invoice metadata schema: missing metadata_version and no legacy invoice fields."
  );
}

// ─── Create-flow mapper ───────────────────────────────────────────────────────

/**
 * Map a `CreateInvoiceFormData` object (from the create wizard) plus the
 * already-pinned `docCid` into an `InvoiceMetadataV1Input` that can be
 * passed directly to `uploadValidatedInvoiceMetadata`.
 *
 * This is the single, shared mapper for both the live service and any future
 * server-side flows.  Keeping it here (next to the schema) means the mapping
 * is always co-located with the Zod definitions it must satisfy.
 *
 * @param formData    - The raw form data from the create wizard.
 * @param ownerAddress - Stellar G-address of the invoice issuer / SME.
 * @param docCid      - IPFS CID of the already-pinned PDF document.
 */
export function formDataToMetadataV1Input(
  formData: import("@/types").CreateInvoiceFormData,
  ownerAddress: string,
  docCid: string
): InvoiceMetadataV1Input {
  // Compute effective APR for the attributes array
  const daysToMaturity = Math.ceil(
    (new Date(formData.dueDate).getTime() -
      new Date(formData.listingExpiryDate).getTime()) /
      (1000 * 60 * 60 * 24)
  );
  const effectiveAPR =
    daysToMaturity > 0 && formData.discountRate > 0 && formData.discountRate < 1
      ? (formData.discountRate / (1 - formData.discountRate)) *
        (365 / daysToMaturity) *
        100
      : 0;

  return {
    // ── NFT standard fields ─────────────────────────────────────────────
    name: `Invoice ${formData.invoiceNumber}`,
    description:
      formData.description?.trim() ||
      `Tokenized invoice ${formData.invoiceNumber} — ${formData.debtorName}`,
    // Placeholder — uploadValidatedInvoiceMetadata will replace this with
    // the real SVG/thumbnail CID after generating the preview image.
    image: `ipfs://${docCid}`,

    // ── Invoice identity ────────────────────────────────────────────────
    invoice_number: formData.invoiceNumber,
    amount: formData.amount,
    currency: formData.currency,
    // Normalise to YYYY-MM-DD so it always matches the schema regex
    due_date: formData.dueDate.slice(0, 10),

    // ── Parties ─────────────────────────────────────────────────────────
    issuer: {
      address: ownerAddress,
    },
    debtor: {
      name: formData.debtorName,
      address: formData.debtorAddress || undefined,
      privacy: formData.debtorPrivacy ?? "full",
    },

    // ── Enrichment ───────────────────────────────────────────────────────
    jurisdiction: formData.jurisdiction as InvoiceMetadataV1Input["jurisdiction"],
    category: formData.category as InvoiceMetadataV1Input["category"],
    discount_rate: formData.discountRate,
    ipfs_document_cid: docCid,

    // ── Pre-built attributes (APR as an extra trait) ──────────────────
    attributes: [
      { trait_type: "Invoice Number", value: formData.invoiceNumber },
      { trait_type: "Currency", value: formData.currency },
      { trait_type: "Amount", value: formData.amount, display_type: "number" },
      { trait_type: "Due Date", value: formData.dueDate.slice(0, 10) },
      ...(formData.jurisdiction
        ? [{ trait_type: "Jurisdiction", value: formData.jurisdiction }]
        : []),
      ...(formData.category
        ? [{ trait_type: "Category", value: formData.category }]
        : []),
      {
        trait_type: "Discount Rate",
        value: Math.round(formData.discountRate * 100),
        display_type: "boost_percentage" as const,
      },
      ...(effectiveAPR > 0
        ? [
            {
              trait_type: "Effective APR",
              value: Math.round(effectiveAPR * 100) / 100,
              display_type: "number" as const,
            },
          ]
        : []),
    ],
  };
}

/** UI descriptor for a metadata version badge. */
export interface MetadataVersionBadge {
  label: string;
  tone: "success" | "warning" | "info";
  description: string;
}

/**
 * Map a detected metadata version to a display badge.
 * Used by the metadata viewer to surface the schema version to users.
 */
export function metadataVersionBadge(
  version: MetadataVersion | "unknown"
): MetadataVersionBadge {
  switch (version) {
    case "1.0":
      return {
        label: `Schema v${METADATA_VERSION}`,
        tone: "success",
        description: "Current versioned metadata schema.",
      };
    case "legacy":
      return {
        label: "Legacy schema",
        tone: "warning",
        description:
          "Pre-versioned metadata, migrated to the current schema for display.",
      };
    default:
      return {
        label: "Unknown schema",
        tone: "info",
        description: "Metadata schema could not be identified.",
      };
  }
}
